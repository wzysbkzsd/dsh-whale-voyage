/**
 * 确定性选取文案：稀有成因有专属池，普通/变体走场景池。
 * salt 使用卡序号（单调递增），同一航次卡片不重复取同一索引序列。
 */
export function captionFor(kind: RareKind | 'scene', scene: Scene, salt: number): CaptionPair {
  const pool = kind === 'scene' ? SCENE_CAPTIONS[scene] : RARE_CAPTIONS[kind]
  if (pool === undefined || pool.length === 0) return { zh: '在海上', en: 'At sea' }
  const index = ((salt % pool.length) + pool.length) % pool.length
  return pool[index]
}
